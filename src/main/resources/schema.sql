-- Схема БД музея. Скрипт выполняется пользователем-владельцем схемы (museum_owner)
-- при старте приложения (spring.sql.init) и идемпотентен.

CREATE TABLE IF NOT EXISTS app_user (
    enabled boolean not null default true,
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    name          VARCHAR(150) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    CONSTRAINT uk_app_user_username UNIQUE (username),
    CONSTRAINT ck_app_user_role CHECK (role IN ('ADMIN', 'CURATOR'))
);

CREATE TABLE IF NOT EXISTS exhibition_hall (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100)  NOT NULL,
    area         NUMERIC(10, 2) NOT NULL,
    is_available BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_exhibition_hall_name UNIQUE (name),
    CONSTRAINT ck_exhibition_hall_area CHECK (area > 0)
);

CREATE TABLE IF NOT EXISTS exhibit (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_number VARCHAR(50)   NOT NULL,
    name             VARCHAR(150)  NOT NULL,
    condition        VARCHAR(20)   NOT NULL,
    required_area    NUMERIC(10, 2) NOT NULL,
    CONSTRAINT uk_exhibit_inventory_number UNIQUE (inventory_number),
    CONSTRAINT ck_exhibit_condition CHECK (condition IN ('EXCELLENT', 'GOOD', 'DAMAGED', 'RESTORATION', 'LOST')),
    CONSTRAINT ck_exhibit_required_area CHECK (required_area > 0)
);

CREATE TABLE IF NOT EXISTS exhibition (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(150) NOT NULL,
    start_date TIMESTAMP    NOT NULL,
    end_date   TIMESTAMP    NOT NULL,
    status     VARCHAR(20)  NOT NULL,
    curator_id BIGINT       NOT NULL,
    CONSTRAINT fk_exhibition_curator FOREIGN KEY (curator_id) REFERENCES app_user (id) ON DELETE RESTRICT,
    CONSTRAINT ck_exhibition_period CHECK (end_date > start_date),
    CONSTRAINT ck_exhibition_status CHECK (status IN ('PLANNED', 'ACTIVE', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE IF NOT EXISTS exhibit_placement (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exhibit_id    BIGINT      NOT NULL,
    exhibition_id BIGINT      NOT NULL,
    hall_id       BIGINT      NOT NULL,
    status        VARCHAR(20) NOT NULL,
    placed_at     TIMESTAMP,
    removed_at    TIMESTAMP,
    CONSTRAINT fk_placement_exhibit FOREIGN KEY (exhibit_id) REFERENCES exhibit (id) ON DELETE RESTRICT,
    CONSTRAINT fk_placement_exhibition FOREIGN KEY (exhibition_id) REFERENCES exhibition (id) ON DELETE RESTRICT,
    CONSTRAINT fk_placement_hall FOREIGN KEY (hall_id) REFERENCES exhibition_hall (id) ON DELETE RESTRICT,
    CONSTRAINT uk_placement_exhibit_exhibition UNIQUE (exhibit_id, exhibition_id),
    CONSTRAINT ck_placement_status CHECK (status IN ('PLANNED', 'INSTALLED', 'REMOVED')),
    CONSTRAINT ck_placement_removed_at CHECK ((status = 'REMOVED') = (removed_at IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS idx_exhibition_curator ON exhibition (curator_id);
CREATE INDEX IF NOT EXISTS idx_placement_hall ON exhibit_placement (hall_id);
CREATE INDEX IF NOT EXISTS idx_placement_exhibition ON exhibit_placement (exhibition_id);
